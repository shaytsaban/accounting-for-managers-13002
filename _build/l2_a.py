def ALLOW(yrs, rr, plug_x, req_x, wo=(None, None), op_x=('', '')):
    """Stages 3 and 4 by year: the allowance at the start, write-offs against it, the expense that completes it, the required balance."""
    rows = [RW('o', ['הלח״מ בפתיחה (1.1)'] + [C(r['a0'], f'=B#c#' if j else '', op_x[j]) for j, r in enumerate(rr)])]
    if any(wo):
        rows.append(RW('w', ['חוב אבוד שנמחק כנגד ההפרשה'] + [C(-w[0], '', w[1]) if w else '' for w in wo]))
    rows += [RW('e', ['הוצאות הלח״מ: ההשלמה (שלב 4)'] + [C(r['exp'], '', plug_x[j]) for j, r in enumerate(rr)], 'plug'),
             RW('c', ['הלח״מ בסגירה: הנדרש (31.12)'] + [C(r['a'], '', req_x[j]) for j, r in enumerate(rr)], 'bal')]
    # the required balance comes before the expense: it is the target, and the expense completes the way to it
    for j in range(len(rr)):
        base = 100 * (j + 1)
        rows[0]['c'][j + 1]['o'] = base + 1
        if any(wo) and rows[1]['c'][j + 1] != '': rows[1]['c'][j + 1]['o'] = base + 2
        rows[-1]['c'][j + 1]['o'] = base + 3
        rows[-2]['c'][j + 1]['o'] = base + 4
    return STG('שלבים 3 ו-4', 'תנועת ההלח״מ: מן הפתיחה אל הנדרש, וההשלמה היא ההוצאה', yrs, rows, widths=[46, 27, 27], center=True)


