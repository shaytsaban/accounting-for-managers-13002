def RECV(years):
    """years: dicts with credit sales, credits to credit customers, collections, write-offs, specific (gross, rate) or None, general rate.
    Returns the gross, allowance, expense and net balance of every year."""
    out, g, a = [], 0, 0
    for y in years:
        g0, a0 = g, a
        g = g0 + y['cs'] - y.get('cr', 0) - y['col'] - y.get('wo', 0)
        sp = y.get('spec')
        spa = round(sp[0] * sp[1]) if sp else 0
        ga = round((g - (sp[0] if sp else 0)) * y['rate'])
        a = spa + ga
        exp = a - a0 + y.get('wo', 0)
        out.append(dict(g0=g0, a0=a0, g=g, spa=spa, ga=ga, a=a, exp=exp, net=g - a, rest=g - (sp[0] if sp else 0)))
    return out


def INV(lots, sales, price, cts):
    """lots: (units, unit cost) in time order, the first being the opening balance. sales: (units, price).
    Returns closing units, FIFO and periodic average cost, net realisable value, carrying amounts, cost of sales and gross profit."""
    tu = sum(q for q, c in lots); tc = sum(q * c for q, c in lots)
    su = sum(q for q, p in sales); rev = sum(q * p for q, p in sales)
    cu = tu - su
    left, fifo, parts = cu, 0, []
    for q, c in reversed(lots):
        t = min(q, left)
        if t: fifo += t * c; parts.append((t, c))
        left -= t
        if not left: break
    avg_u = tc / tu
    avg = cu * avg_u
    nrv_u = price - cts
    nrv = cu * nrv_u
    r = dict(tu=tu, tc=tc, su=su, rev=rev, cu=cu, fifo=fifo, parts=parts, avg_u=avg_u, avg=avg, nrv_u=nrv_u, nrv=nrv, open=lots[0][0] * lots[0][1], buy=tc - lots[0][0] * lots[0][1])
    for m in ('fifo', 'avg'):
        r[m + '_bv'] = min(r[m], nrv)
        r[m + '_wd'] = r[m] - r[m + '_bv']
        r[m + '_cogs'] = tc - r[m + '_bv']
        r[m + '_gp'] = rev - r[m + '_cogs']
        r[m + '_cogs0'] = tc - r[m]
        r[m + '_gp0'] = rev - r[m + '_cogs0']
    return r


def ERRS(gp, err):
    """gp: reported gross profit per year. err: misstatement of the closing inventory of each year, + overstated, - understated.
    Correcting closing inventory moves the profit of that year the other way to the error; the next year's opening moves it back."""
    rows, prev = [], 0
    for y, e in zip(gp, err):
        po, pc = prev, -e
        rows.append(dict(gp=y, po=po, pc=pc, fixed=y + po + pc))
        prev = e
    return rows


