def QX(key, title, kind, story, asks, steps, check=(), tip=None, pun=None, sm=False, data=''):
    """An exercise with a full story. The question stays in the right column on every slide of its solution.
    kind: 'together' (we solve it together) or 'alone' (answer boxes first, the full solution after).
    steps: (heading, items); an item is a sentence, ('c', label, expression[, note]) for a calculation line, or ('h', html[, height])."""
