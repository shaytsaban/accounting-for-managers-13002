def LAYERS(lots, sold, mode, st=1, W=1120, H=250, unit='יח׳'):
    """Inventory as layers in time order, oldest on the right. mode 'fifo': the oldest units leave first.
    mode 'avg': the layers melt into one average cost. Revealed step by step from st."""
    tot = sum(q for q, c in lots)
    x0, x1, y0, h = 30, W - 30, 70, 64
    sc = (x1 - x0) / tot
    pal = ['#bfe7e1', '#c9d8ff', '#ffe0b3', '#e2d4ff', '#ffd1d6', '#d6f0c8']
    g, x, step = [], x1, st
    for i, (q, c) in enumerate(lots):
        w = q * sc
        g.append(f'<g class="st" data-n="{step * 10}"><rect x="{x - w + 1:.1f}" y="{y0}" width="{w - 2:.1f}" height="{h}" rx="6" fill="{pal[i % 6]}" stroke="#1b2d55" stroke-width="1.5"/>'
                 + _t(x - w / 2, y0 + 28, f'{q:,} {unit}', 19) + _t(x - w / 2, y0 + 52, f'× {c:,}', 18, '#2a3858', 600)
                 + _t(x - w / 2, y0 - 12, 'הישן ביותר' if i == 0 else ('החדש ביותר' if i == len(lots) - 1 else ''), 16, '#5d6a86', 600) + '</g>')
        x -= w
    step += 1
    tc = sum(q * c for q, c in lots)
    if mode == 'avg':
        a = tc / tot
        g.append(f'<g class="st" data-n="{step * 10}"><rect x="{x0}" y="{y0}" width="{x1 - x0}" height="{h}" rx="6" fill="#f4e9c9" stroke="#a86703" stroke-width="2"/>'
                 + _t((x0 + x1) / 2, y0 + 30, f'{tot:,} {unit} בעלות ממוצעת', 20, '#8a5300') + _t((x0 + x1) / 2, y0 + 54, f'{tc:,} ÷ {tot:,} = {a:,.2f}'.replace('.00', ''), 19, '#8a5300', 700) + '</g>')
        step += 1
    ws = sold * sc
    g.append(f'<g class="st" data-n="{step * 10}"><rect x="{x1 - ws:.1f}" y="{y0 - 4}" width="{ws:.1f}" height="{h + 8}" rx="8" fill="#16213a" fill-opacity=".14" stroke="#e0454f" stroke-width="3" stroke-dasharray="7 5"/>'
             + f'<path d="M{x1 - ws + 4:.1f} {y0 + h + 18} H{x1 - 4}" stroke="#e0454f" stroke-width="3"/>' + _t(x1 - ws / 2, y0 + h + 44, f'נמכרו {sold:,} {unit}: עלות המכר', 19, '#b3262f') + '</g>')
    step += 1
    g.append(f'<g class="st" data-n="{step * 10}"><path d="M{x0 + 4} {y0 + h + 18} H{x1 - ws - 4:.1f}" stroke="#25a65f" stroke-width="3"/>' + _t((x0 + x1 - ws) / 2, y0 + h + 44, f'נשארו {tot - sold:,} {unit}: מלאי הסגירה', 19, '#167a43') + '</g>')
    g.append(_t(W / 2, 24, '←  סדר הכניסה למלאי', 17, '#5d6a86', 600))
    return f'<svg class="ill" dir="ltr" viewBox="0 0 {W} {H}" role="img">' + ''.join(g) + '</svg>'


def VLINE(pts, st=1, W=1120, H=300):
    """Value of a trading portfolio at each date, with the gain or loss of each period. pts: (date, value[, extra label])."""
    lo, hi = min(p[1] for p in pts), max(p[1] for p in pts)
    pad = (hi - lo) * .35 or 1
    lo, hi = lo - pad, hi + pad
    x0, x1, yb, yt = 90, W - 90, H - 60, 40
    X = lambda i: x1 - i * (x1 - x0) / (len(pts) - 1)
    Y = lambda v: yb - (v - lo) / (hi - lo) * (yb - yt)
    out = [f'<line x1="{x0 - 40}" y1="{yb}" x2="{x1 + 40}" y2="{yb}" stroke="#1b2d55" stroke-width="2"/>']
    for i, p in enumerate(pts):
        d, v = p[0], p[1]
        g = ''
        if i:
            pv = pts[i - 1][1]
            ch = v - pv
            col = '#25a65f' if ch >= 0 else '#e0454f'
            g += f'<line x1="{X(i - 1):.1f}" y1="{Y(pv):.1f}" x2="{X(i):.1f}" y2="{Y(v):.1f}" stroke="#1b2d55" stroke-width="3"/>'
            g += f'<rect x="{(X(i - 1) + X(i)) / 2 - 66:.1f}" y="{(Y(pv) + Y(v)) / 2 - 40:.1f}" width="132" height="30" rx="15" fill="{col}"/>'
            g += _t((X(i - 1) + X(i)) / 2, (Y(pv) + Y(v)) / 2 - 19, ('רווח ' if ch >= 0 else 'הפסד ') + f'{abs(ch):,}', 17, '#fff')
        g += f'<circle cx="{X(i):.1f}" cy="{Y(v):.1f}" r="8" fill="#ff6a4d" stroke="#1b2d55" stroke-width="2"/>' + _t(X(i), Y(v) + 30, f'{v:,}', 19)
        g += _t(X(i), yb + 26, d, 17, '#2a3858', 600)
        if len(p) > 2: g += _t(X(i), yb + 48, p[2], 16, '#167a43', 700)
        out.append(f'<g class="st" data-n="{(st + i) * 10}">{g}</g>')
    return f'<svg class="ill" dir="ltr" viewBox="0 0 {W} {H}" role="img">' + ''.join(out) + '</svg>'


