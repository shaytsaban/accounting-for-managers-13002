def DT(head, rows, cls=''):
    """A small data table inside a question."""
    h = ''.join(f'<th>{TX(x)}</th>' for x in head)
    b = ''.join('<tr>' + ''.join(f'<td>{TX(str(c))}</td>' for c in r) + '</tr>' for r in rows)
    return f'<table class="dt {cls}"><tr>{h}</tr>{b}</table>'


def _xh(it):
    """Rough height of one solution item, for splitting long solutions."""
    if isinstance(it, tuple):
        if it[0] == 'c': return 44 + (24 if len(it) > 3 and it[3] else 0) + (32 if len(it[1]) + len(it[2]) > 52 else 0)
        if it[0] == 'h': return it[2] if len(it) > 2 else 120
    return (len(re.sub(r'<[^>]+>|\$', '', it)) // 44 + 1) * 31 + 6


def _xi(it, n):
    if isinstance(it, tuple):
        if it[0] == 'c': return CL(it[1], it[2], n, it[3] if len(it) > 3 else '')
        if it[0] == 'h': return ST(n, it[1])
    return ST(n, TX(it), 'p')


