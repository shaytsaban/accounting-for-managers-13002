def BASE(p, x_res, x_life):
    """Steps 2 and 3: the depreciable amount and the depreciation of a full year."""
    return STG('שלבים 2 ו-3', 'בסיס הפחת, ופחת לשנה מלאה', ['', 'ש״ח'], [
        RW('c', ['עלות (שלב 1)', C(p['cost'], '', 'העלות שחישבנו בחלק הקודם: רק מה שנכנס לטור ״לעלות הנכס״.')], 'prev'),
        RW('r', ['בניכוי ערך שייר', C(-p['res'], '', x_res, hl=('res',))]),
        RW('b', ['בסיס הפחת', C(p['base'], '=B#c#:B#r#', f'${f2(p["cost"])} - {f2(p["res"])} = {f2(p["base"])}$. זה החלק של העלות שנצרך לאורך החיים.')], 'bal'),
        RW('l', ['חלקי אורך החיים, בשנים', C(p['life'], '', x_life, hl=('life',))]),
        RW('a', ['פחת לשנה מלאה', C(p['annual'], '=B#b#:B#l#', f'${f2(p["base"])} ÷ {p["life"]} = {f2(p["annual"])}$ בכל שנה מלאה.')], 'net')], widths=[62, 38])


def BVT(p, end, lab, months, ask=()):
    """Step 5 at one date: cost less the accumulated depreciation."""
    a = p['acc'](end)
    return STG(5, f'ערך בספרים ליום {lab}', ['', 'ש״ח'], [
        RW('c', ['עלות', C(p['cost'], '', 'העלות לא משתנה לאורך השנים.')], 'prev'),
        RW('a', ['בניכוי פחת נצבר', C(-a, '', f'{months} חודשים מן הזמינות לשימוש: ${f2(p["annual"])} × {months} ÷ 12 = {f2(a)}$.', hl=('avail',) + tuple(ask))]),
        RW('b', ['ערך בספרים: במאזן', C(p['cost'] - a, '=B#c#:B#a#', f'${f2(p["cost"])} - {f2(a)} = {f2(p["cost"] - a)}$.')], 'net')], widths=[62, 38])


def DEPYRS(p, yrs, start_lab, x_first):
    """The year table: cost, accumulated depreciation, book value at each date, and the year's depreciation."""
    dates = [(start_lab, None)] + [(f'31.12.{y}', (y + 1, 1)) for y in yrs]
    cols = [''] + [d for d, _ in dates]
    acc = [0 if e is None else p['acc'](e) for _, e in dates]
    rows = BYCOL([
        RW('c', ['עלות'] + [C(p['cost'], '', 'העלות לא משתנה.') for _ in dates]),
        RW('a', ['פחת נצבר'] + [C(-a, '', 'אין עדיין פחת: הנכס רק נעשה זמין.' if not i else f'כל הפחת עד {dates[i][0]}: ${f2(acc[i - 1])} + {f2(acc[i] - acc[i - 1])} = {f2(acc[i])}$.') for i, a in enumerate(acc)]),
        RW('b', ['ערך בספרים: במאזן'] + [C(p['cost'] - a, f'={LET[i + 1]}#c#:{LET[i + 1]}#a#', f'${f2(p["cost"])} - {f2(a)} = {f2(p["cost"] - a)}$.') for i, a in enumerate(acc)], 'net'),
        RW('e', ['הוצאות הפחת של השנה'] + [''] + [C(acc[i] - acc[i - 1], '', x_first if i == 1 else 'שנה מלאה: ' + f2(p['annual']) + '.') for i in range(1, len(acc))], 'plug')])
    return STG(5, 'פחת נצבר וערך בספרים, תאריך אחר תאריך', cols, rows, widths=[28] + [72 / len(dates)] * len(dates), center=True)


