# ================================================================ the numbers
def PPE(cost, res, life, start):
    """Straight-line depreciation from the first of the month the asset is available (start = (year, month))."""
    annual = (cost - res) / life
    acc = lambda end: annual * MONTHS(start, end) / 12
    return dict(cost=cost, res=res, life=life, base=cost - res, annual=annual, acc=acc, bv=lambda end: cost - acc(end))


