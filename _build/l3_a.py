def COSTX(key, title, kind, story, asks, cur, pts, pays, total_x, tip, live, axis_title='שלושה תאריכים, גבול אחד: מתי הנכס זמין לשימוש?'):
    """A cost question in two slides: the time axis (step 1), then the sorting table and the total (steps 2 and 3)."""
    XQ(key, title, kind, story, asks, [
        dict(cur=cur, stages=[AXIS(pts, PRE_X, POST_X, axis_title)]),
        dict(cur=cur, stages=[SORT3(pays, 'עלות הרכוש הקבוע', total_x)], after=[('tip', tip)] if tip else [])],
       flow=FLOW_C, live=live)


def COSTLIVE(pays, hints, widths=(240, 130, 130)):
    """The same sorting table as a live sheet: every payment is typed in its column, and the cost column is summed."""
    cost = [i for i, p in enumerate(pays) if p[2] == 'c']
    rows = [LR(f'i{i}', [lab, v if to == 'c' else '', v if to == 'e' else ''], 'לעלות: חיוני, ולפני שהנכס זמין.' if to == 'c' else 'חלק מן השימוש: מקלידים בטור ההוצאה.') for i, (lab, v, to, xp, k) in enumerate(pays)]
    assert cost == list(range(len(cost)))
    rows.append(LR('t', ['עלות הרכוש הקבוע', (f'=SUM(B#i0#:B#i{cost[-1]}#)', sum(pays[i][1] for i in cost)), ''], 'סוכמים רק את הטור ״לעלות הנכס״.', 'net'))
    return LIVE(['התשלום', 'לעלות הנכס', 'הוצאה'], rows, list(widths), hints=hints)


