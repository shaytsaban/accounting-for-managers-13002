def COSTT(rows, total, included_x, excl=()):
    """Stages 1 to 4 of cost: every payment with where it goes, then the total of what enters the cost."""
    r = [RW(f'i{i}', [lab, C(v, '', x)]) for i, (lab, v, x) in enumerate(rows)]
    r += [RW(f'x{i}', [lab, C('הוצאה', '', x)], 'out') for i, (lab, x) in enumerate(excl)]
    r.append(RW('t', ['עלות הרכוש הקבוע', C(total, f'=B#i0#:B#i{len(rows) - 1}#', included_x)], 'net'))
    return STG('שלבים 1 עד 4', 'מה שולם, ומה נכנס לעלות', ['תשלום', 'לעלות (ש״ח)'], r, widths=[64, 36])


