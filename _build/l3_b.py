        RW('r', ['הכנסות שכירות', C(rent_y, '', 'זהה בשני המודלים.'), C(rent_y, '', 'זהה בשני המודלים.')]),
        RW('v', ['שינוי בשווי', C(ch, '', 'ההפרש מן השווי הקודם עובר לרווח והפסד.'), C('אין רישום', '', 'במודל העלות שינויי השווי לא נרשמים.')]),
        RW('d', ['פחת', C('אין', '', 'במודל השווי ההוגן אין פחת.'), C(-dep, '', 'פחת על חלק המבנה בלבד.')]),
        RW('t', ['סך ההשפעה על רווח והפסד', C(pl_fv, '=B#r#:B#v#', f'שכירות ושינוי בשווי: {f2(pl_fv)}.'), C(pl_c, '=C#r#:C#d#', f'שכירות פחות פחת: {f2(pl_c)}.')], 'net'),
