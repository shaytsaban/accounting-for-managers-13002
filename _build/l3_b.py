RDC = ['', 'עלות', 'מחקר או פיתוח?', 'ההשלמה צפויה?', 'התקרה', 'נכס', 'הוצאה']
RDW = [16, 12, 17, 17, 12, 13, 13]


def RDT(rows, title, total=None):
    """One row per year or project; every cell appears on its own click: cost, stage, chance, ceiling, asset, expense.
    rows: (key, label, cost, x_cost, stage, x_stage, chance, x_chance, ceiling, x_ceiling, asset, x_asset)."""
    out = []
    for i, (k, lab, c, xc, stg, xs, ch, xch, cap, xcap, a, xa) in enumerate(rows):
        o = lambda j: (i + 1) * 10 + j
        out.append(RW(k, [lab, C(c, '', xc, o(1), hl=(k,)), C(stg, '', xs, o(2), hl=(k,)), C(ch, '', xch, o(3), hl=(k,)) if ch else '', C(cap, '', xcap, o(4), hl=(k,)) if cap else '',
                          C(a, '', xa, o(5)), C(c - a, f'=B#{k}#+F#{k}#', f'עלות פחות נכס: ${c} - {a} = {c - a}$.', o(6))], 'net' if a else ''))
    if total:
        tc, ta = sum(r[2] for r in rows), sum(r[10] for r in rows)
        assert (ta, tc - ta) == total
        out.append(RW('t', ['סך הכול', C(tc, '', 'סך העלויות של השנה.'), '', '', '', C(ta, f'=F#{rows[0][0]}#:F#{rows[-1][0]}#', f'סך הנכס: {ta}.'), C(tc - ta, f'=G#{rows[0][0]}#:G#{rows[-1][0]}#', f'סך ההוצאה: {tc - ta}.')], 'bal'))
    return STG(None, title, RDC, out, widths=RDW, center=True)


