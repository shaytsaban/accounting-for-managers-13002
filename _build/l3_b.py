def FVT(rows_, title):
    out = []
    for k, d, ev, v, ch, nt in rows_:
        out.append(RW(k, [d, ev, C(v, '', nt.get('v', ''), hl=(k,)), C(ch, nt.get('f', ''), nt.get('ch', '')) if ch != '' else '', C(ch, '', nt.get('ef', '')) if ch != '' else '']))
    return STG(None, title, TP, out, widths=TPW, dcol=0, center=True)


def FVLIVE(rows_, hints):
    r = []
    for i, (k, d, ev, v, ch, nt) in enumerate(rows_):
        if not i: r.append(LR(k, [d, v], 'העלות: השווי הראשון.'))
        else: r.append(LR(k, [d, v, (f'=B#{k}#-B#{rows_[i - 1][0]}#', ch)], 'השווי פחות השווי בשורה הקודמת. כותבים פעם אחת וגוררים למטה.' if i == 1 else '', 'net' if i == len(rows_) - 1 else ''))
    return LIVE(['תאריך', 'שווי הוגן', 'שינוי: לרווח והפסד'], r, [150, 140, 170], center='A', hints=hints)


